"""中文分词。

入库和查询【两侧都必须用这个文件里的函数】。
如果两侧口径不一致（比如入库用精确模式、查询用别的模式），
就会出现"明明有这个词却搜不到"的诡异现象。
"""

import logging

import jieba

# jieba 第一次运行会往控制台打印"Building prefix dict..."，关掉它
jieba.setLogLevel(logging.WARNING)

# --------------------------------------------------------------------------- #
# 领域自定义词典（修复坑 3：分词错误）
# --------------------------------------------------------------------------- #
# 为什么要手动维护这个？
# 实测案例（当时用的演示语料）：
#     原文「边缘计算业务线由林澈负责」
#     jieba 默认切成：业务 | 线由林澈 | 负责
#     「林澈」被吞进了一个不存在的长词里，查询「林澈」永远匹配不到这一块。
#
# 中文人名绝大多数是 2 个字，恰恰是 jieba 最容易切错的一类。
#
# ⚠️ 下面这些词对应的是【已归档的演示语料】，当前语料（Vue 文档）里一个都不出现。
#    留着它们是无害的（add_word 对不出现的词没有任何影响），
#    改它们则会改变分词结果 → 让所有历史评测报告失效 —— 所以不动。
#    真实项目里这个词典应该从配置或文件加载、可持续维护。
DOMAIN_WORDS = [
    # 人名
    "林澈", "周牧", "陈砚舟", "苏晚",
    # 公司与机构
    "星澜科技", "恒远半导体", "启明创投", "云澜数据",
    # 产品与型号
    "澜芯", "澜图", "HC-300", "HC-500",
    # 地名（保证粒度稳定）
    "无锡市", "杭州市", "成都市",
]

for _word in DOMAIN_WORDS:
    jieba.add_word(_word)


def segment_for_index(text: str) -> str:
    """【入库用】精确模式，返回用空格连接的一整串。

    为什么要空格连接？因为 PostgreSQL 的 simple 分词器按空格切词。
    我们替它把中文切好，它就只需要按空格再切一下，就得到正确的词了。
    """
    return " ".join(w.strip() for w in jieba.cut(text) if w.strip())


def segment_for_query(text: str) -> list[str]:
    """【查询用】搜索模式，返回词列表。

    和入库用的精确模式有什么区别？实测：
        jieba.cut("无锡市在哪里")            -> ["无锡市", "在", "哪里"]
        jieba.cut_for_search("无锡市在哪里") -> ["无锡", "无锡市", "在", "哪里"]
                                                      ↑
                                        多切出一个「无锡」，正好补上粒度差

    这就是修复坑 2（粒度不匹配）的办法：
    库里存的是「无锡市」，用户可能查「无锡」，搜索模式能把长词再切细一遍。

    代价是查询词变多、引入噪音，靠 BM25 的 IDF 把噪音压下去。
    """
    return [w.strip() for w in jieba.cut_for_search(text) if w.strip()]